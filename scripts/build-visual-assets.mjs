import { access, mkdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(scriptDir, "..");
const rawRoot = path.join(
  root,
  "design-sources",
  "visual-overhaul",
  "raw"
);
const outputRoot = path.join(root, "src", "assets", "generated");
const qaRoot = path.join(root, "work", "visual-qa");

const materials = [
  { key: "basaltInk", source: "basalt-ink.png", output: "basalt-ink" },
  {
    key: "coolLimestone",
    source: "cool-limestone.png",
    output: "cool-limestone",
  },
  {
    key: "firedTerracotta",
    source: "fired-terracotta.png",
    output: "fired-terracotta",
  },
  { key: "darkGrout", source: "dark-grout.png", output: "dark-grout" },
  {
    key: "papyrusFiber",
    source: "papyrus-fiber.png",
    output: "papyrus-fiber",
  },
];

const reliefIds = Array.from({ length: 13 }, (_, index) => `l${index + 1}`);
const reliefSizes = [
  { name: "thumb", width: 320, quality: 76, budget: 90_000 },
  { name: "mobile", width: 640, quality: 80, budget: 240_000 },
  { name: "hero", width: 1024, quality: 82, budget: 520_000 },
];

const sourceName = (lessonId) =>
  `${lessonId[0]}${String(Number(lessonId.slice(1))).padStart(2, "0")}.png`;

async function requireFile(filePath) {
  try {
    await access(filePath);
  } catch {
    throw new Error(`Missing visual source: ${path.relative(root, filePath)}`);
  }
}

async function writeWebp(input, output, width, quality) {
  await sharp(input)
    .rotate()
    .resize(width, width, {
      fit: "cover",
      position: "centre",
      withoutEnlargement: true,
    })
    .webp({
      quality,
      alphaQuality: 100,
      effort: 6,
      smartSubsample: true,
    })
    .toFile(output);
}

async function assertBudget(filePath, budget) {
  const details = await stat(filePath);
  if (details.size > budget) {
    throw new Error(
      `${path.relative(root, filePath)} is ${details.size} bytes; budget is ${budget}`
    );
  }
  return details.size;
}

await mkdir(path.join(outputRoot, "materials"), { recursive: true });
await mkdir(path.join(outputRoot, "reliefs"), { recursive: true });
await mkdir(qaRoot, { recursive: true });

const materialImports = [];
const materialEntries = [];
const budgetRows = [];

for (const material of materials) {
  const input = path.join(rawRoot, "materials", material.source);
  const filename = `${material.output}-512.webp`;
  const output = path.join(outputRoot, "materials", filename);
  await requireFile(input);
  await writeWebp(input, output, 512, 72);
  const bytes = await assertBudget(output, 150_000);
  materialImports.push(
    `import ${material.key} from "./materials/${filename}";`
  );
  materialEntries.push(`  ${material.key},`);
  budgetRows.push({ file: filename, bytes });
}

const reliefImports = [];
const reliefEntries = [];
const contactTiles = [];

for (const lessonId of reliefIds) {
  const input = path.join(rawRoot, "reliefs", sourceName(lessonId));
  await requireFile(input);
  const source = sharp(input).rotate();
  const metadata = await source.metadata();
  if (
    !metadata.width ||
    !metadata.height ||
    Math.min(metadata.width, metadata.height) < 1000 ||
    metadata.width !== metadata.height
  ) {
    throw new Error(`${sourceName(lessonId)} must be at least 1000px square`);
  }

  const names = {};
  for (const size of reliefSizes) {
    const symbol = `${lessonId}${size.name[0].toUpperCase()}${size.name.slice(1)}`;
    const filename = `${lessonId}-${size.width}.webp`;
    const output = path.join(outputRoot, "reliefs", filename);
    await writeWebp(input, output, size.width, size.quality);
    const bytes = await assertBudget(output, size.budget);
    reliefImports.push(`import ${symbol} from "./reliefs/${filename}";`);
    names[size.name] = symbol;
    budgetRows.push({ file: filename, bytes });
  }

  reliefEntries.push(
    `  ${lessonId}: { thumb: ${names.thumb}, mobile: ${names.mobile}, hero: ${names.hero} },`
  );

  contactTiles.push({
    input: await sharp(input)
      .resize(240, 240, { fit: "cover", position: "centre" })
      .jpeg({ quality: 82 })
      .toBuffer(),
    left: ((Number(lessonId.slice(1)) - 1) % 4) * 240,
    top: Math.floor((Number(lessonId.slice(1)) - 1) / 4) * 240,
  });
}

const manifest = `/* This file is generated by scripts/build-visual-assets.mjs. */
${materialImports.join("\n")}
${reliefImports.join("\n")}

export const MATERIAL_TEXTURES = Object.freeze({
${materialEntries.join("\n")}
});

export const LESSON_RELIEFS = Object.freeze({
${reliefEntries.join("\n")}
});

export function reliefForLesson(lessonId) {
  return LESSON_RELIEFS[lessonId] || LESSON_RELIEFS.l4;
}
`;

await writeFile(
  path.join(outputRoot, "visualManifest.generated.js"),
  manifest,
  "utf8"
);

await sharp({
  create: {
    width: 960,
    height: 960,
    channels: 3,
    background: "#111316",
  },
})
  .composite(contactTiles)
  .jpeg({ quality: 88, mozjpeg: true })
  .toFile(path.join(qaRoot, "relief-contact-sheet.jpg"));

const sourceDigest = await Promise.all(
  [...materials.map((item) => path.join(rawRoot, "materials", item.source)), ...reliefIds.map((id) => path.join(rawRoot, "reliefs", sourceName(id)))].map(
    async (filePath) => {
      const data = await readFile(filePath);
      return `${path.relative(rawRoot, filePath)}:${data.byteLength}`;
    }
  )
);

await writeFile(
  path.join(qaRoot, "asset-report.json"),
  `${JSON.stringify(
    {
      generatedAt: new Date().toISOString(),
      sources: sourceDigest,
      outputs: budgetRows,
      totalOutputBytes: budgetRows.reduce((sum, row) => sum + row.bytes, 0),
    },
    null,
    2
  )}\n`,
  "utf8"
);

console.log(
  `Built ${materials.length} materials and ${reliefIds.length * reliefSizes.length} relief assets.`
);
