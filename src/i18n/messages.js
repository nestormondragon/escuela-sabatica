export const MESSAGES = Object.freeze({ es, en });

export function translateMessage(locale, key, values = {}) {
  const normalized = normalizeLocale(locale);
  const message = MESSAGES[normalized][key] ?? MESSAGES.es[key] ?? key;
  return String(message).replace(/\{(\w+)\}/g, (match, name) =>
    values[name] == null ? match : String(values[name])
  );
}
